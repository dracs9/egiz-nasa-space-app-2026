import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, expect, it, vi } from 'vitest';
import { PreferenceExplorer } from './PreferenceExplorer';
import { useAppStore } from '../state/store';
import { pilotTestData } from '../data/testData';
import type { CampaignModel } from './CampaignPage';
import { designCampaigns } from '../lib/campaign';
import * as downloads from '../lib/download';
let root: Root | null = null;
afterEach(async () => { if (root) await act(async () => root!.unmount()); root = null; vi.restoreAllMocks(); document.body.innerHTML = ''; });
it('switches an observed winner and applies exactly the displayed two-objective decision', async () => {
  (globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }).IS_REACT_ACT_ENVIRONMENT = true;
  window.history.replaceState(null, '', '#/campaign?data=pilot');
  useAppStore.setState({ dataMode: 'pilot' }); useAppStore.getState().initialize(pilotTestData, 'pilot');
  const state = useAppStore.getState();
  const run = pilotTestData.results.runs.find(r => r.target === state.targetId)!;
  const template = pilotTestData.templates.templates.find(t => t.id === run.template)!;
  const model: CampaignModel = { run, template, campaigns: run.campaigns, globalCampaigns: run.campaigns, pending: false, error: null, live: false, ms: 0 };
  document.body.innerHTML = '<div id="preference-test"></div>'; root = createRoot(document.getElementById('preference-test')!);
  await act(async () => root!.render(<PreferenceExplorer model={model} />));
  expect(document.querySelector('.preference-winner')?.textContent).toContain('Death Valley');
  const interval = document.querySelector<HTMLButtonElement>('.preference-band button')!;
  await act(async () => interval.click());
  expect(document.querySelector('.preference-winner')?.textContent).toContain('Rio Tinto');
  const apply = [...document.querySelectorAll('button')].find(b => b.textContent?.includes('Apply these priorities'))!;
  await act(async () => apply.click());
  const applied = useAppStore.getState();
  expect(applied.k).toBe(1); expect(applied.enabledObjectives).toEqual(['O1', 'O2']);
  expect(applied.weights!.O1 + applied.weights!.O2).toBeCloseTo(3, 11);
  const campaign = designCampaigns(run, template, pilotTestData.candidates.tiles, applied.enabledObjectives, applied.weights, 'global')[0];
  expect(campaign.sites[0].id).toBe('PILOT_RIO_TINTO');
  expect(document.body.textContent).toContain('Applied to one-site campaign');
  const download = vi.spyOn(downloads, 'downloadJson').mockImplementation(() => {});
  const exportButton = [...document.querySelectorAll('button')].find(b => b.textContent === 'Export analysis')!;
  exportButton.click();
  const payload = download.mock.calls[0][0] as { synthetic: boolean; source_inputs: unknown; lines: { id: string; right: number | null }[]; intervals: { start: number; end: number }[] };
  expect(payload.synthetic).toBe(false);
  expect(payload.source_inputs).toEqual(pilotTestData.results.inputs);
  expect(payload.lines).toHaveLength(8);
  expect(payload.lines.some(l => l.id === 'KZ_E051.200_N43.400')).toBe(false);
  expect(payload.intervals[0].end).toBeCloseTo(.16968240719550248, 12);
});
