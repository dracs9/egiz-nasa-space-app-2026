"""Multi-day CSPICE illumination record for a world package.

python -m pipeline.world.illumination mars-jezero --days 3

Concatenates consecutive 24 h runs of the existing pipeline.science.spice.geometry();
no vectors are interpolated, extrapolated or generated by any other method.
"""
from __future__ import annotations

import argparse
import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

from pipeline.science.spice import DEFAULT_EPOCH, geometry
from pipeline.world.scene import ROOT, SITES


def build(name: str, days: int = 3, epoch: str = DEFAULT_EPOCH, step: float = 600) -> Path:
    if not 1 <= days <= 10:
        raise ValueError("days must be 1-10")
    if name.startswith("earth:"):
        from pipeline.world.scene import earth_site
        window = name.split(":", 1)[1]
        site, name = earth_site(window), f"earth-{window.lower()}"
    else:
        site = SITES[name]
    start = datetime.fromisoformat(epoch.replace("Z", "+00:00")).astimezone(timezone.utc)
    record, samples = None, []
    for day in range(days):
        part = geometry({"id": site["id"], "body": site["body"], "lat": site["lat"], "lon": site["lon"]},
                        (start + timedelta(days=day)).isoformat().replace("+00:00", "Z"), 86400, step)
        record = record or part
        samples += [{**s, "t": s["t"] + day * 86400.0} for s in part["samples"] if day == 0 or s["t"] > 0]
    assert record is not None  # days >= 1
    document = {**record, "schema": "egiz.world_illumination", "duration": days * 86400.0, "samples": samples,
                "segments": days, "method": "Concatenated consecutive 24 h CSPICE geometry runs; identical kernels and frame."}
    path = ROOT / "data/world" / name / "illumination.json"
    path.write_text(json.dumps(document, allow_nan=False, separators=(",", ":")) + "\n")
    print(f"{name}: {len(samples)} CSPICE samples over {days} d from {document['epochUtc']}")
    return path


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("site", help=f"one of {sorted(SITES)} or earth:<discovery window id>")
    parser.add_argument("--days", type=int, default=3)
    args = parser.parse_args()
    build(args.site, args.days)
