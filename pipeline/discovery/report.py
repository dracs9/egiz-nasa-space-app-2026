"""Write docs/discovery/RESULTS.md from the built bundle and validation record (no hand-typed numbers).

python -m pipeline.discovery report
"""
from __future__ import annotations

import json

from pipeline.discovery import OUT, ROOT

DOC = ROOT / "docs" / "discovery" / "RESULTS.md"


def _f(v, nd=3):
    return "—" if v is None else f"{v:.{nd}f}" if isinstance(v, float) else str(v)


def write_report() -> str:
    b = json.loads((OUT / "discovery.json").read_text())
    v = json.loads((OUT / "validation.json").read_text()) if (OUT / "validation.json").exists() else None
    idx = json.loads((OUT / "index" / "manifest.json").read_text())
    W = b["windows"]
    name = dict(zip(W["id"], W["name"]))
    country = dict(zip(W["id"], W["country"]))
    novelty = dict(zip(W["id"], W["novelty_class"]))
    sites = {s["id"]: s["name"] for s in b["benchmark_sites"]}
    L = ["# EGIZ Discovery Engine — results", "",
         f"Generated by `python -m pipeline.discovery report` from bundle {b['version']} "
         f"(content sha256 `{b['content_sha256'][:16]}…`, built {b['generated_at']}). Not synthetic.", "",
         "## Earth-wide index", "",
         f"* Windows acquired by the index run: **{idx['n_windows']}** "
         f"({', '.join(f'{k}: {n}' for k, n in idx['by_pool'].items())}).",
         f"* Coverage levels: {', '.join(f'{k} {n}' for k, n in idx['by_coverage_level'].items())}.",
         "* Stage failures (recorded, not hidden): " + ("; ".join(f"{k} × {n}" for k, n in idx["failures"].items()) or "none") + ".",
         f"* Earth windows ranked (index + geo-0.1.0): **{len(W['id'])}**; reference population: {b['population']['definition']}.",
         f"* Targets scored: {', '.join(t['id'] for t in b['targets'])}.", ""]
    for t in b["targets"]:
        L += [f"## {t['name']} ({t['id']})", "",
              "Diversified shortlist, general profile (score = fidelity × coverage; 90 % interval on fidelity).", "",
              "| # | Window | Country | Score | Fidelity [90 %] | Coverage | Evidence | Earth pct | Novelty |",
              "|---|---|---|---|---|---|---|---|---|"]
        for n, e in enumerate(t["shortlist"][:10], 1):
            L.append(f"| {n} (rank {e['rank']}) | {name[e['window']]} `{e['window']}` | {country[e['window']] or '—'} | "
                     f"{_f(e['score'])} | {_f(e['fidelity'], 2)} [{_f(e['lo'], 2)}–{_f(e['hi'], 2)}] | {_f(e['coverage'], 2)} | "
                     f"{e['category']} | {_f(e['score_percentile'], 1)} | {novelty[e['window']]} |")
        hyp = [x for x in t["benchmark"] if x["role"] == "hypothesis"]
        if hyp:
            L += ["", "Kazakhstan hypotheses (not forced): " + "; ".join(
                f"{sites[x['site']]} rank {x.get('rank', '—')} (pct {_f(x.get('score_percentile'), 1)})" for x in hyp) + "."]
        top = t["shortlist"][0]
        if top.get("rover"):
            r = top["rover"]["deltas"]["earth_mass_matched"]
            L += ["", f"Rover experiment on the top window (model estimate): a mass-matched Earth test mis-states the target "
                      f"slope limit by {_f(r['d_slope_limit_deg'], 1)}°, traversable fraction by "
                      f"{_f(r['d_traversable_frac'] * 100, 1)} points, sinkage ×{_f(r['sinkage_ratio'], 2)}, "
                      f"climbing energy ×{_f(r['energy_ratio'], 2)}."]
        L.append("")
    if v:
        L += ["## Validation", "", f"Population: {v['population']}. Draws: {v['draws']}.", "",
              "| Target | n positives | ROC AUC [90 % bootstrap] | AUC vs controls | recall@50 | precision@50 (chance) | seed ρ |",
              "|---|---|---|---|---|---|---|"]
        for r in v["targets"]:
            m = r["metrics"]
            ci = m.get("auc_90ci") or ["—", "—"]
            L.append(f"| {r['target']} | {m['n_positive']} | {m['auc']} [{ci[0]}–{ci[1]}] | {m['auc_vs_designated_controls']} | "
                     f"{m['recall@50']} | {m['precision@50']} ({m['chance_precision']}) | {r['reproducibility']['spearman_seed_2026_vs_7']} |")
        L += ["", "Ablation (AUC without each dimension) and weight sensitivity:", ""]
        for r in v["targets"]:
            abl = ", ".join(f"{d} {a}" for d, a in r["ablation_auc_without"].items())
            L.append(f"* {r['target']}: {abl}; AUC under weight perturbation p05/p50/p95 = "
                     f"{r['sensitivity']['auc_p05_p50_p95']}; top-10 Jaccard {r['sensitivity']['top10_jaccard_p05_p50_p95']}.")
        L += ["", "Caveats:", ""] + [f"* {c}" for c in v["caveats"]] + [""]
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text("\n".join(L) + "\n", encoding="utf-8")
    return str(DOC)
